# English name -> Czech name, from the framework table (domain, sin, virtue columns)
CZ = {}
for en, cz in zip(LANG['EN']['rows'], LANG['CZ']['rows']):
    for k in (0, 1, 3):
        CZ.setdefault(en[k], cz[k])


def name(opt, lang):
    if '|' in opt:
        return opt.split('|')[lang == 'CZ']
    return opt if lang == 'EN' else CZ[opt]


def questions(lang):
    """Multiple choice: a = options, c = index of the correct one (rotates so it is not always first)."""
    ask = 'What is this?' if lang == 'EN' else 'Co to je?'
    head = 'Scenarios · ' if lang == 'EN' else 'Situace · '
    out = []
    for n, (dom, diff, ans, wrong, en, en_w, cz, cz_w) in enumerate(S):
        text, why = (en, en_w) if lang == 'EN' else (cz, cz_w)
        opts = [name(o, lang) for o in wrong]
        c = n % 4
        opts.insert(c, name(ans, lang))
        assert len(set(opts)) == 4, (n, opts)
        prompt = text if text.endswith('?') else f'{text} <b>{ask}</b>'
        out.append(dict(t=text[:46], d=diff, g=head + name(dom, lang), p=prompt, h='', s='', o=False, k='mc', a=opts, c=c, w=why))
    return out
