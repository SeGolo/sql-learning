def questions():
    out = []
    for topic, words in V.items():
        rows = ''.join(f'<tr><td>{en}</td><td><b>{cz[0]}</b>{"<br><small>also: " + ", ".join(cz[1:]) + "</small>" if len(cz) > 1 else ""}</td><td>{note}</td></tr>'
                       for en, cz, note, _ in words)
        lesson = (f'<p>Read the list, say each word aloud, then practise. Gender helps later grammar: '
                  f'<i>ten</i> = masculine, <i>ta</i> = feminine, <i>to</i> = neuter.</p>'
                  f'<table><thead><tr><th>English</th><th>Czech</th><th>note</th></tr></thead><tbody>{rows}</tbody></table>')
        out.append(dict(t='Word list: ' + topic.split(' · ', 1)[1], d='Easy', g=topic, p=lesson, h='', s='', o=False, k='lesson', a=''))
        for en, cz, note, diff in words:
            out.append(dict(t=en, d=diff, g=topic, p=f'Translate into Czech: <b>{en}</b>',
                            h=f'Starts with „{cz[0][:2]}…“ · {len(cz[0])} letters',
                            s='', o=False, k='cz', a=cz, w=f'<b>{cz[0]}</b>' + (f' (also: {", ".join(cz[1:])})' if len(cz) > 1 else '') + f' · {note}'))
    return out
